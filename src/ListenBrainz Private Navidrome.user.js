// ==UserScript==
// @name        ListenBrainz: Private Navidrome
// @namespace   https://musicbrainz.org/user/chaban
// @version     1.0.0
// @description Connects BrainzPlayer directly to a private, Tailscale, or LAN-hosted Navidrome/Subsonic server without public exposure.
// @tag         ai-created
// @author      chaban
// @license     MIT
// @homepageURL https://github.com/chaban-mb/userscripts
// @supportURL  https://github.com/chaban-mb/userscripts/issues
// @match       https://*.listenbrainz.org/*
// @icon        https://listenbrainz.org/static/img/favicon-256.png
// @grant       GM.getValue
// @grant       GM.setValue
// @grant       GM.deleteValue
// @grant       GM.registerMenuCommand
// @run-at      document-start
// @updateURL   https://github.com/chaban-mb/userscripts/raw/main/src/ListenBrainz%20Private%20Navidrome.user.js
// @downloadURL https://github.com/chaban-mb/userscripts/raw/main/src/ListenBrainz%20Private%20Navidrome.user.js
// ==/UserScript==

(async function () {
    'use strict';

    const SCRIPT_NAME = GM.info.script.name;
    const STORAGE_KEY = 'UserJS.ListenBrainz.PrivateNavidrome.Config';
    const REQUIRED_KEYS = ['instance_url', 'username', 'salt', 'md5_auth_token'];

    const log = {
        debug: (...args) => console.debug(`[${SCRIPT_NAME}]`, ...args),
        info: (...args) => console.info(`[${SCRIPT_NAME}]`, ...args),
        warn: (...args) => console.warn(`[${SCRIPT_NAME}]`, ...args),
        error: (...args) => console.error(`[${SCRIPT_NAME}]`, ...args),
    };

    /**
     * Parses and validates a raw JSON configuration string or object.
     *
     * @param {string|object|null} raw - Raw JSON string or object from GM storage or prompt input.
     * @returns {{instance_url: string, username: string, salt: string, md5_auth_token: string}|null}
     */
    function parseAndValidateConfig(raw) {
        if (!raw) return null;
        try {
            const parsed = typeof raw === 'string' ? JSON.parse(raw) : raw;
            if (!parsed || typeof parsed !== 'object') return null;
            const isValid = REQUIRED_KEYS.every(
                (key) => typeof parsed[key] === 'string' && parsed[key].trim().length > 0
            );
            if (!isValid) return null;
            return {
                instance_url: parsed.instance_url.trim().replace(/\/+$/, ''),
                username: parsed.username.trim(),
                salt: parsed.salt.trim(),
                md5_auth_token: parsed.md5_auth_token.trim(),
            };
        } catch {
            return null;
        }
    }

    /**
     * Prompts the user for the JSON configuration generated by the Python one-liner.
     */
    async function promptForConfig() {
        const currentStored = await GM.getValue(STORAGE_KEY, '');
        const currentRaw =
            typeof currentStored === 'string'
                ? currentStored
                : currentStored
                  ? JSON.stringify(currentStored)
                  : '';
        const input = window.prompt(
            'Paste the JSON configuration generated by the Python one-liner (leave empty to clear):',
            currentRaw
        );
        if (input === null) return;

        if (input.trim() === '') {
            await GM.deleteValue(STORAGE_KEY);
            log.info('Cleared private Navidrome configuration.');
            location.reload();
            return;
        }

        const validated = parseAndValidateConfig(input);
        if (!validated) {
            window.alert(
                'Invalid configuration JSON. Expected keys: instance_url, username, salt, md5_auth_token.'
            );
            return;
        }

        await GM.setValue(STORAGE_KEY, JSON.stringify(validated));
        log.info('Saved private Navidrome configuration for:', validated.instance_url);
        location.reload();
    }

    GM.registerMenuCommand('Configure Private Navidrome...', promptForConfig);

    const config = parseAndValidateConfig(await GM.getValue(STORAGE_KEY, null));
    if (!config) {
        log.info(
            'No private Navidrome configuration found. Use the userscript menu "Configure Private Navidrome..." to set up.'
        );
        return;
    }

    /**
     * Patches the #global-react-props script element before React hydrates GlobalAppContext.
     *
     * @param {HTMLScriptElement} scriptEl - The #global-react-props element.
     */
    function patchGlobalProps(scriptEl) {
        try {
            const props = JSON.parse(scriptEl.textContent);
            props.navidrome = config;
            scriptEl.textContent = JSON.stringify(props);
            log.info('Connected BrainzPlayer to private Navidrome:', config.instance_url);
        } catch (err) {
            log.error('Failed to patch global-react-props:', err);
        }
    }

    const existing = document.getElementById('global-react-props');
    if (existing && existing.textContent) {
        patchGlobalProps(existing);
        return;
    }

    const observer = new MutationObserver((_mutations, obs) => {
        const el = document.getElementById('global-react-props');
        if (el && el.textContent) {
            patchGlobalProps(el);
            obs.disconnect();
        }
    });

    observer.observe(document.documentElement, {
        childList: true,
        subtree: true,
    });

    document.addEventListener('DOMContentLoaded', () => observer.disconnect(), { once: true });
})();
